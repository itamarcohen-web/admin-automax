// Runs after `next build`.
//  1. Next.js' static export contains two small INLINE scripts per page (flight-data bootstrap). They are moved, byte for byte, into
//     /_next/static/inline/<sha256>.js and replaced by <script src>. Order and behaviour are unchanged (still synchronous), and the
//     Content-Security-Policy can then forbid every inline script instead of listing hashes.
//  2. out/_headers is written for Cloudflare Pages (Vercel uses the committed vercel.json, which carries the same headers).
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import nextEnv from '@next/env'
import { buildCsp, OTHER_HEADERS } from './security-headers.mjs'

nextEnv.loadEnvConfig(process.cwd())
const OUT = join(process.cwd(), 'out')
if (!existsSync(OUT)) throw new Error('out/ not found: run `next build` first')

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) yield* walk(p)
    else yield p
  }
}

const INLINE_DIR = join(OUT, '_next', 'static', 'inline')
mkdirSync(INLINE_DIR, { recursive: true })
let pages = 0
let moved = 0
const files = new Set()
for (const file of walk(OUT)) {
  if (!file.endsWith('.html')) continue
  pages++
  const html = readFileSync(file, 'utf8')
  const next = html.replace(/<script(?<attrs>[^>]*)>(?<body>[\s\S]*?)<\/script>/g, (all, attrs, body) => {
    if (/\bsrc\s*=/.test(attrs) || body.trim() === '') return all
    if (/type\s*=\s*["']application\/(ld\+)?json["']/.test(attrs)) return all   // data block, never executed
    const name = `${createHash('sha256').update(body, 'utf8').digest('hex').slice(0, 32)}.js`
    if (!files.has(name)) { writeFileSync(join(INLINE_DIR, name), body, 'utf8'); files.add(name) }
    moved++
    return `<script${attrs} src="/_next/static/inline/${name}"></script>`
  })
  if (next !== html) writeFileSync(file, next, 'utf8')
}

// nothing executable may remain inline
for (const file of walk(OUT)) {
  if (!file.endsWith('.html')) continue
  for (const m of readFileSync(file, 'utf8').matchAll(/<script(?<attrs>[^>]*)>(?<body>[\s\S]*?)<\/script>/g)) {
    const { attrs, body } = m.groups
    if (!/\bsrc\s*=/.test(attrs) && body.trim() !== '' && !/application\/(ld\+)?json/.test(attrs)) throw new Error(`postbuild: inline script left in ${file}`)
  }
}

const supabaseUrl = (process.env.NEXT_PUBLIC_SUPABASE_URL ?? '').trim().replace(/\/+$/, '')
if (!supabaseUrl) throw new Error('NEXT_PUBLIC_SUPABASE_URL is not set: the CSP cannot name the Supabase host')

const headers = `# Generated by scripts/postbuild.mjs - do not edit by hand. (Cloudflare Pages. Vercel uses vercel.json.)
/*
  Content-Security-Policy: ${buildCsp(supabaseUrl)}
${Object.entries(OTHER_HEADERS).map(([k, v]) => `  ${k}: ${v}`).join('\n')}

/_next/static/*
  Cache-Control: public, max-age=31536000, immutable
`
writeFileSync(join(OUT, '_headers'), headers)
console.log(`postbuild: ${pages} pages, ${moved} inline scripts moved to ${files.size} files, strict CSP -> out/_headers`)
